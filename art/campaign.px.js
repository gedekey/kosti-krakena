// Щупальце от (x0, y0) вверх на h; толщина у основания w0; присоски цветом rim.
function tentacle(c, x0, y0, h, amp, ph, col, w0, rim) {
  for (let i = 0; i < h; i++) {
    const t = i / h, x = Math.round(x0 + Math.sin(t * 5 + ph) * amp * t)
    const w = Math.max(1, Math.round(w0 * (1 - t)))
    c.hline(x - (w >> 1), y0 - i, w, col)
    if (rim && w > 2 && i % 4 === 0) c.px(x + (w >> 1) - 1, y0 - i, rim)
  }
}

// Прядь водорослей вниз от (x0, y0).
function seaweed(c, x0, y0, len, ph) {
  for (let i = 0; i < len; i++) {
    const x = Math.round(x0 + Math.sin(i * 0.3 + ph) * 2)
    const w = i < len * 0.7 ? 2 : 1
    c.px(x - 1, y0 + i, "K")
    c.hline(x, y0 + i, w, i % 5 === 4 ? "L" : "G")
  }
}

